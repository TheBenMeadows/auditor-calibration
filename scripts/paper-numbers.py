pa = load("pa", ROOT / "scripts" / "panel-agreement.py")


def pct(x, nd=1):
    return f"{100 * x:.{nd}f}\\%"


def dec(x, nd=3):
    return f"{x:.{nd}f}"


def sgn(x, nd=3):
    return f"{x:+.{nd}f}"


def pv(p, floored=False):
    if floored:
        return f"$<${p:.4f}"
    if p >= 0.01:
        return f"{p:.3f}" if p < 0.995 else "1.000"
    return f"{p:.4f}" if p >= 0.0001 else "$<$0.0001"


class Numbers:
    def __init__(self):
        self.vals = collections.OrderedDict()

    def __setitem__(self, k, v):
        if k in self.vals and self.vals[k] != v:
            raise SystemExit(f"number {k} set twice with different values: {self.vals[k]} / {v}")
        self.vals[k] = v

    def tex(self):
        lines = ["% Generated by scripts/paper-numbers.py from analysis.json and the probe/panel rows. Do not edit.",
                 "\\makeatletter",
                 "\\newcommand{\\N}[1]{\\@ifundefined{pn@#1}{\\errmessage{undefined number #1}}{\\@nameuse{pn@#1}}}"]
        lines += [f"\\@namedef{{pn@{k}}}{{{v}}}" for k, v in self.vals.items()]
        return "\n".join(lines + ["\\makeatother", ""])


def pair(rows, a, b):
    for r in rows:
        if (r["a"], r["b"]) == (a, b):
            return r, 1
        if (r["a"], r["b"]) == (b, a):
            return r, -1
    raise KeyError((a, b))


def lane_numbers(N, rep):
    for lane, r in rep["lanes"].items():
        k, m, ci = KEY[lane], r["metrics"], r["ci"]
        N[f"{k}-auroc"] = dec(m["auroc"])
        N[f"{k}-auroc-lo"], N[f"{k}-auroc-hi"] = dec(ci["auroc"][0]), dec(ci["auroc"][1])
        for met in ("recall", "specificity", "accuracy"):
            N[f"{k}-{met}"] = pct(m[met])
        for met in ("recall", "specificity"):
            N[f"{k}-{met}-lo"], N[f"{k}-{met}-hi"] = pct(ci[met][0]), pct(ci[met][1])
        N[f"{k}-brier"] = dec(m["brier"])
        o = r["original"]["metrics"]
        N[f"{k}-orig-auroc"], N[f"{k}-orig-spec"] = dec(o["auroc"]), pct(o["specificity"])
        N[f"{k}-runs"] = str(r["rows"])
        N[f"{k}-missing"] = str(len(r["failures"]["missing"]["model"]) + len(r["failures"]["missing"]["infrastructure"]))
        w = r["sensitivity"]["without_outside_files"]
        N[f"{k}-inside-auroc"], N[f"{k}-inside-spec"] = dec(w["auroc"]), pct(w["specificity"])
        fw = r["sensitivity"]["failed_wrong"]
        N[f"{k}-fw-recall"], N[f"{k}-fw-spec"] = pct(fw["recall"]), pct(fw["specificity"])
        ps = r["per_source"]
        if "squint" in ps:
            N[f"{k}-squint-spec"] = pct(ps["squint"]["false"][0])
        c = rep["cost"][lane]
        N[f"{k}-cost"] = f"{c['reported_cost_usd']:.2f}"
        N[f"{k}-latency"] = f"{c['mean_latency_s']:.0f}"
        N[f"{k}-tools"] = f"{c['mean_tool_calls']:.1f}"
        N[f"{k}-verdict"] = pct(c["verdict_agreement"])
    N["claude-cost"] = f"{sum(round(rep['cost'][l]['reported_cost_usd'], 2) for l in ('Opus 5.5', 'Fable 5.1', 'Sonnet 5.5', 'Haiku 5.5')):.2f}"
    N["runs-total"] = f"{sum(r['rows'] for r in rep['lanes'].values()):,}".replace(",", "{,}")
    b = rep["opus_batches"]
    (k1, m1), (k2, m2) = list(b.items())
    N["opus-b1-auroc"], N["opus-b2-auroc"] = dec(m1["auroc"]), dec(m2["auroc"])
    N["families"], N["largest-family"] = str(rep["families"]), str(rep["largest_family"])
    N["boot"] = f"{rep['bootstrap_draws']:,}".replace(",", "{,}")
    N["source-rule"] = f"{rep['source_rule']['right']}/{rep['source_rule']['n']}"
    N["source-rule-pct"] = pct(rep["source_rule"]["accuracy"])
    sources, labels = ap.case_sources()
    N["source-rule-auroc"] = dec(ap.auroc([1.0 if sources[c] == "original" else 0.0 for c in sources if labels[c] == 1],
                                          [1.0 if sources[c] == "original" else 0.0 for c in sources if labels[c] == 0]))
    N["source-rule-below"] = ", ".join(l for l, r in rep["lanes"].items() if r["metrics"]["auroc"] < ap.auroc(
        [1.0 if sources[c] == "original" else 0.0 for c in sources if labels[c] == 1], [1.0 if sources[c] == "original" else 0.0 for c in sources if labels[c] == 0]))


def pairwise_numbers(N, rep):
    au = rep["comparisons"]["auroc"]
    for a, b in (("Opus 5.5", "SWE-2 High"), ("Opus 5.5", "Haiku 5.5"), ("Opus 5.5", "Sonnet 5.5"), ("Fable 5.1", "SWE-2 High")):
        r, s = pair(au, a, b)
        k = f"au-{KEY[a]}-{KEY[b]}"
        N[f"{k}-diff"] = sgn(s * r["diff"])
        lo, hi = sorted((s * r["ci"][0], s * r["ci"][1]))
        N[f"{k}-lo"], N[f"{k}-hi"] = sgn(lo), sgn(hi)
        N[f"{k}-p"], N[f"{k}-holm"] = pv(r["p"], r["p_floored"]), pv(r["p_holm"], r["p_floored"])
        N[f"{k}-cp"], N[f"{k}-choolm"] = pv(r["p_centred"], r["p_centred_floored"]), pv(r["p_centred_holm"], r["p_centred_floored"])
        N[f"{k}-small"] = f"{r['small_tail']:.0f}"
        if r.get("single_run"):
            sr = r["single_run"]
            N[f"{k}-sr-diff"] = sgn(s * sr["diff_median"])
            if "p_median" in sr:
                N[f"{k}-sr-p"], N[f"{k}-sr-share"] = pv(sr["p_median"]), pct(sr["survive_share"])
    N["au-tail-survivors"] = str(sum(1 for r in au if r["p_holm"] < 0.05))
    N["au-centred-survivors"] = str(sum(1 for r in au if r["p_centred_holm"] < 0.05))
    for fam, short in (("accuracy", "acc"), ("specificity", "spec"), ("recall", "rec")):
        for r in rep["comparisons"][fam]:
            s = 1
            a, b = r["a"], r["b"]
            k = f"{short}-{KEY[a]}-{KEY[b]}"
            N[f"{k}-diff"], N[f"{k}-holm"] = sgn(s * r["diff"]), pv(r["p_holm"])
            if r.get("single_run"):
                N[f"{k}-sr-p"], N[f"{k}-sr-share"] = pv(r["single_run"]["p_median"]), pct(r["single_run"]["survive_share"])


def derived_numbers(N, rep):
    """Numbers the prose states as summaries of a table: each is computed here so the
    audit can recompute it."""
    au = rep["comparisons"]["auroc"]
    core = {"Opus 5.5", "Fable 5.1", "Sonnet 5.5", "DeepSeek Flash"}
    rest = [r for r in au if r["p_holm"] >= 0.05]

    def bound(rows):  # rounded outward, so the printed bound is never inside an interval
        return math.ceil(max(max(abs(r["ci"][0]), abs(r["ci"][1])) for r in rows) * 1000) / 1000
    N["bound-core"] = f"{bound([r for r in rest if {r['a'], r['b']} <= core]):.3f}"
    N["bound-haiku"] = f"{bound([r for r in rest if 'Haiku 5.5' in (r['a'], r['b']) and 'SWE-2 High' not in (r['a'], r['b'])]):.3f}"
    N["bound-swe2"] = f"{bound([r for r in rest if 'SWE-2 High' in (r['a'], r['b'])]):.3f}"
    oh, _ = pair(au, "Opus 5.5", "Haiku 5.5")
    N["au-opus-haiku-holm-mc"] = f"{2 * math.sqrt(oh['small_tail']) / oh['kept'] * (oh['p_holm'] / oh['p']):.2f}"
    tds = list(rep["target_definition"].values())
    for i, td in enumerate(tds, 1):
        drop = rep["lanes"]["Opus 5.5"]["metrics"]["auroc"] - td["lanes"]["Opus 5.5"]["auroc"]
        N[f"td{i}-opus-drop"] = dec(drop)
        N[f"td{i}-drop-exceeds"] = str(sum(1 for r in au if abs(r["diff"]) < drop))
    N["lane-gap-max"] = dec(max(abs(r["diff"]) for r in au))
    N["outside-n"] = str(len(ap.OUTSIDE_FILES))
    mc = rep["mutation_classes"]
    c_vals = [d["mutated C"][0] for d in mc.values()]
    c_rest = [d["mutated C without count tolerance"][0] for d in mc.values()]
    N["classC-rest-min"], N["classC-rest-max"] = pct(min(c_rest), 0), pct(max(c_rest), 0)
    N["classC-rest-n"] = str(next(iter(mc.values()))["mutated C without count tolerance"][1])
    N["classC-full-lanes"] = str(sum(1 for d in mc.values() if d["mutated C without count tolerance"][0] == 1))
    nat = [d[k][0] for d in mc.values() for k in ("original", "council", "squint")]
    N["classC-min"], N["classC-max"] = pct(min(c_vals), 0), pct(max(c_vals), 0)
    N["natural-min"], N["natural-max"] = pct(min(nat), 0), pct(max(nat), 0)
    others = [rep["lanes"][l]["per_source"]["squint"]["false"][0] for l in rep["lanes"] if l != "SWE-2 High"]
    N["squint-spec-others-min"], N["squint-spec-others-max"] = pct(min(others)), pct(max(others))
    sources, labels = ap.case_sources()
    rows, _ = ap.load_lane(ap.LANES["SWE-2 High"])
    t = ap.case_table(rows, labels)[0]
    loss = {c: 1 - v["correct"] for c, v in t.items() if v["label"] == 0}
    N["swe2-outside-loss-share"] = pct(sum(v for c, v in loss.items() if c in ap.OUTSIDE_FILES) / sum(loss.values()), 0)


def sensitivity_numbers(N, rep):
    """Calibration bins and the pairwise survivors under the sensitivity checks the prose cites."""
    for lane, bins in rep["calibration"].items():
        for i, b in enumerate(bins, 1):
            if b["n"]:
                N[f"cal-{KEY[lane]}-b{i}-n"], N[f"cal-{KEY[lane]}-b{i}-mean"], N[f"cal-{KEY[lane]}-b{i}-share"] = str(b["n"]), dec(b["mean_p"], 2), dec(b["real_share"], 2)
    for key, prefix in (("failed_wrong_comparisons", "fw"), ("inside_comparisons", "in")):
        for fam, short in (("accuracy", "acc"), ("recall", "rec"), ("specificity", "spec")):
            for r in rep[key][fam]:
                N[f"{prefix}-{short}-{KEY[r['a']]}-{KEY[r['b']]}-holm"] = pv(r["p_holm"])
    for key, prefix in (("failed_wrong_comparisons", "fw"), ("inside_comparisons", "in")):
        r, _ = pair(rep[key]["auroc"], "Opus 5.5", "Haiku 5.5")
        N[f"{prefix}-au-opus-haiku-holm"] = pv(r["p_holm"], r.get("p_floored"))
    N["outside-false"] = str(len(ap.OUTSIDE_FILES) - sum(1 for c in ap.OUTSIDE_FILES if ap.case_sources()[1][c] == 1))


def harness_numbers(N, rep):
    hd = rep.get("harness")
    if not hd:
        return
    for name, r in hd["lanes"].items():
        k = KEY[r["model"]] + "-inline"
        m, ci = r["metrics"], r["ci"]
        N[f"{k}-auroc"], N[f"{k}-auroc-lo"], N[f"{k}-auroc-hi"] = dec(m["auroc"]), dec(ci["auroc"][0]), dec(ci["auroc"][1])
        for met in ("recall", "specificity", "accuracy"):
            N[f"{k}-{met}"] = pct(m[met])
        N[f"{k}-brier"], N[f"{k}-runs"] = dec(m["brier"]), str(r["rows"])
        N[f"{k}-missing"] = str(len(r["failures"]["missing"]["model"]) + len(r["failures"]["missing"]["infrastructure"]))
        N[f"{k}-cost"] = f"{r['cost']['reported_cost_usd']:.2f}"
    for i, r in enumerate(hd["contrasts"]["auroc"]):
        ka, kb = (KEY.get(r["a"]) or KEY[r["a"].replace(" inline", "")] + "-inline"), (KEY.get(r["b"]) or KEY[r["b"].replace(" inline", "")] + "-inline")
        k = f"hd-{ka}-{kb}"
        N[f"{k}-diff"], N[f"{k}-lo"], N[f"{k}-hi"] = sgn(r["diff"]), sgn(r["ci"][0]), sgn(r["ci"][1])
        N[f"{k}-holm"], N[f"{k}-choolm"] = pv(r["p_holm"], r.get("p_floored")), pv(r["p_centred_holm"], r.get("p_centred_floored"))
        for fam, short in (("accuracy", "acc"), ("recall", "rec"), ("specificity", "spec")):
            c = hd["contrasts"][fam][i]
            N[f"{k}-{short}-diff"], N[f"{k}-{short}-holm"] = sgn(c["diff"]), pv(c["p_holm"])
    # Holm across the four contrasts the plan fixed, with p = 1 for each planned contrast that has no data.
    planned = len(ap.INLINE_CONTRASTS)
    for fam, short in (("auroc", ""), ("accuracy", "-acc"), ("recall", "-rec"), ("specificity", "-spec")):
        rows = hd["contrasts"][fam]
        for r, q in zip(rows, ap.holm([r["p"] for r in rows] + [1.0] * (planned - len(rows)))):
            ka, kb = (KEY.get(r["a"]) or KEY[r["a"].replace(" inline", "")] + "-inline"), (KEY.get(r["b"]) or KEY[r["b"].replace(" inline", "")] + "-inline")
            N[f"hd-{ka}-{kb}{short}-holm-planned"] = pv(q, r.get("p_floored"))
    for model, d in hd["shares"].items():
        for key, v in d.items():
            k = f"share-{KEY[model]}-{key}"
            N[f"{k}"], N[f"{k}-lo"], N[f"{k}-hi"] = dec(v["share"], 2), dec(v["share_ci"][0], 2), dec(v["share_ci"][1], 2)
            N[f"{k}-gap"], N[f"{k}-cond"] = sgn(v["gap"]), sgn(v["condition"])


def tab_harness(rep):
    hd = rep["harness"]
    out = ["\\begin{tabular}{llrrrrrr}", "\\toprule", "A & B & AUROC A$-$B [95\\% CI] & tail $p$ (Holm) & reflected $p$ (Holm) & Accuracy A$-$B (Holm) & Recall A$-$B (Holm) & Specificity A$-$B (Holm) \\\\", "\\midrule"]
    for i, r in enumerate(hd["contrasts"]["auroc"]):
        sec = {f: hd["contrasts"][f][i] for f in ("accuracy", "recall", "specificity")}
        out.append(f"{r['a']} & {r['b']} & {sgn(r['diff'])} [{sgn(r['ci'][0])}, {sgn(r['ci'][1])}] & {pv(r['p_holm'], r.get('p_floored'))} & {pv(r['p_centred_holm'], r.get('p_centred_floored'))} & "
                   + " & ".join(f"{sgn(sec[f]['diff'])} ({pv(sec[f]['p_holm'])})" for f in ("accuracy", "recall", "specificity")) + " \\\\")
    return out + ["\\bottomrule", "\\end{tabular}"]


